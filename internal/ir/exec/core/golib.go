//go:generate go run print_runtime.go

// GoRuntimeFile is the file of the printed compositions in the generated Go runtime, relative to
// the directory of this package. go generate ./gen copies it into the runtime that generated
// parsers embed.
const GoRuntimeFile = "../../../../runtime/call_exec.go"

// RuntimeTag is the build tag that selects the printed compositions in the generated Go runtime
// instead of the hand-written functions they replace.
const RuntimeTag = "pego_exec"

// goSpec is a printed function of the Go runtime: a specialization of a composition for the node
// Parser or the typed TParser.
type goSpec struct {
	fn    string
	typed bool
	on    []string
	name  string // the Go name
}

// goSpecs are the functions of the Go runtime that the compositions replace.
var goSpecs = []goSpec{
	// Parser.Call takes the tracked path for observation and Documents, so it neither observes nor
	// reads a Document itself; a stream may prune a growing start rule's entry.
	{fn: "call", on: []string{ops.Document, ops.Stream}, name: "Call"},
	{fn: "grow", name: "grow"},
	{fn: "call", typed: true, on: []string{ops.Document, ops.Observe, ops.Typed}, name: "callBody"},
	{fn: "callMemo", typed: true, on: []string{ops.Document, ops.Observe, ops.Typed}, name: "CallMemo"},
	{fn: "grow", typed: true, on: []string{ops.Typed}, name: "grow"},
}

// GoRuntime returns the Go file of the printed compositions for package runtime, built with
// RuntimeTag.
func GoRuntime() (string, error) {
	m := Build()
	var b strings.Builder
	fmt.Fprintf(&b, "//go:build %s\n\n// Code generated by internal/ir/exec/core; DO NOT EDIT.\n\npackage runtime\n", RuntimeTag)
	for _, s := range goSpecs {
		f, err := pass.Specialize(m, m.Func(s.fn), s.fn, s.on)
		if err != nil {
			return "", err
		}
		src, err := execgo.Func(m, f, goTarget(s.typed))
		if err != nil {
			return "", err
		}
		b.WriteString("\n" + src)
	}
	return b.String(), nil
}

// goTarget returns the Go implementation of the operations in the node or the typed runtime.
func goTarget(typed bool) *execgo.Target {
	t := &execgo.Target{Recv: "p *Parser", Source: "internal/ir/exec/core"}
	handles := map[string]string{
		ops.Rule: "*Rule", ops.Value: "*Node", ops.Entry: "*memoEntry", ops.Values: "[]any", ops.Errs: "[]*SyntaxError",
		ops.Mark: "ExpMark", ops.Set: "[]ExpID", ops.Kept: "[]ExpID",
	}
	names := map[string]string{"call": "Call", "grow": "grow"}
	entryType, valueField, alloc := "memoEntry", "node", "p.memo.alloc()"
	rule := func(r string) string { return r }
	if typed {
		t.Recv = "p *TParser"
		handles[ops.Rule], handles[ops.Value], handles[ops.Entry] = "*TRule", "any", "*tmemoEntry"
		handles[ops.Body] = "func(*TParser) (any, bool)"
		names = map[string]string{"call": "callBody", "callMemo": "CallMemo", "grow": "grow"}
		entryType, valueField, alloc = "tmemoEntry", "val", "p.memoSlab.one()"
		rule = func(r string) string { return r + ".Rule" }
	}
	t.Handle = func(name string) string { return handles[name] }
	t.FuncName = func(name string) string { return names[name] }
	t.Reg = func(name string) string {
		return map[string]string{ops.Pos: "p.Pos", ops.Silent: "p.Silent"}[name]
	}
	t.Op = func(c *exec.Call, a []string) string {
		switch c.Callee {
		case "call.tracked":
			if typed {
				return "p.TypedDocument != nil"
			}
			return "p.Observation != nil || p.Document != nil"
		case "call.track":
			if typed {
				return fmt.Sprintf("p.DocumentCall(%s, %s, nil)", a[0], a[1])
			}
			return fmt.Sprintf("p.callTracked(%s, %s)", a[0], a[1])
		case "call.trackBody":
			return fmt.Sprintf("p.DocumentCall(%s, 0, %s)", a[0], a[1])
		case "call.spend":
			return "p.Spend()"
		case "call.first":
			return "p.FirstCall(" + rule(a[0]) + ")"
		case "call.growStep":
			return "" // the generated Go runtimes charge no growth step
		case "rule.memo":
			return a[0] + ".Memo"
		case "rule.leader":
			return a[0] + ".Leader"
		case "rule.plain":
			return "len(" + a[0] + ".Scope) == 0"
		case "rule.id":
			return a[0] + ".Id"
		case "rule.invoke":
			return fmt.Sprintf("p.invoke(%s, %s)", a[0], a[1])
		case "rule.invokePlain":
			return fmt.Sprintf("p.invokePlainBody(%s, %s)", a[0], a[1])
		case "rule.run":
			return a[0] + "(p)"
		case "env.memoKey":
			return "p.memoEnv(" + rule(a[0]) + ")"
		case "rec.mark":
			return "len(p.Recovered)"
		case "rec.truncate":
			return "p.Recovered = p.Recovered[:" + a[0] + "]"
		case "rec.since":
			return "p.copyErrors(nil, p.Recovered[" + a[0] + ":])"
		case "rec.add":
			return "p.Recovered = p.copyErrors(p.Recovered, " + a[0] + ")"
		case "rec.none":
			return "len(" + a[0] + ") == 0"
		case "exp.isolate":
			return "p.Isolate(" + a[0] + ")"
		case "exp.unisolate":
			return "p.Unisolate(" + a[0] + ")"
		case "exp.keep":
			return "p.Keep(" + a[0] + ")"
		case "exp.merge", "exp.mergeKept":
			return fmt.Sprintf("p.MergeExpected(%s, %s)", a[0], a[1])
		case "memo.far", "memo.expected", "memo.ok", "memo.end", "memo.growing", "memo.silent", "memo.errs":
			return a[0] + "." + strings.TrimPrefix(c.Callee, "memo.")
		case "memo.value":
			return a[0] + "." + valueField
		case "memo.setExpected":
			return fmt.Sprintf("%s.far, %s.expected = %s, %s", a[0], a[0], a[1], a[2])
		case "memo.grown":
			return fmt.Sprintf("p.memoGet(%s, %s, %s, %s)", a[0], a[1], a[2], a[3])
		case "memo.detached":
			return "&" + entryType + "{}"
		case "memo.finishSeed":
			return fmt.Sprintf("%s.growing = false\n%s.silent = %s", a[0], a[0], a[1])
		case "obs.memoHit":
			return "p.Observation.memoHit()"
		}
		panic("core: no Go implementation of " + c.Callee)
	}
	t.Stmt = func(c *exec.Call, a []string, dst []string, define bool) (string, bool) {
		op := " = "
		if define {
			op = " := "
		}
		key := func() string { return strings.Join(a[:4], ", ") }
		switch c.Callee {
		case "memo.lookup":
			s := dst[0] + op + "p.memoGet(" + key() + ")"
			if dst[1] != "_" {
				s += "\n" + dst[1] + op + dst[0] + " != nil"
			}
			return s, true
		case "memo.store", "memo.seed", "memo.reseed":
			e := dst[0]
			var fields string
			switch c.Callee {
			case "memo.store":
				fields = fmt.Sprintf("%s: %s, ok: %s, end: %s, silent: %s, errs: %s", valueField, a[7], a[4], a[5], a[6], a[8])
			case "memo.seed":
				fields = fmt.Sprintf("end: %s, growing: true", a[1])
			case "memo.reseed":
				fields = fmt.Sprintf("%s: %s, ok: true, end: %s, growing: true, errs: %s", valueField, a[5], a[4], a[6])
			}
			return fmt.Sprintf("%s%s%s\n*%s = %s{%s}\np.memoPut(%s, %s)", e, op, alloc, e, entryType, fields, key(), e), true
		}
		return "", false
	}
	return t
}

// GoFlags returns flags, the GOFLAGS of a go command that builds generated Go parsers, with the
// build tag that selects the printed compositions if this build prints them, so that the parsers
// run the runtime that the generators of this build emit.
func GoFlags(flags string) string {
	if Enabled {
		return flags + " -tags=" + RuntimeTag
	}
	return flags
}
