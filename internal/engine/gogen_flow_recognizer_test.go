// TestGeneratedFlowRecognizerParity runs the generated recognizers printed from Flow IR against the
// engine, on the generated-corpus harness. The route must be taken for some rule of the recognizer table,
// so that the test cannot pass without exercising it. It runs for the fixtures with and without work
// controls.
func TestGeneratedFlowRecognizerParity(t *testing.T) {
	t.Parallel()
	eachMode(t, testGeneratedFlowRecognizerParity)
}

func testGeneratedFlowRecognizerParity(t *testing.T) {
	if testing.Short() {
		t.Skip("builds generated consumers")
	}
	cases := genCorpus(t)
	taken, framed := 0, 0
	gh := &gogen.Hooks{}
	setGenHooks(t, gh)
	gh.LeanRoute = func(table string, r *compile.Rule) {
		if table == "recRules" {
			taken++
		}
	}
	gh.FramedRoute = func(table string, r *compile.Rule) {
		if table == "recRules" {
			framed++
		}
	}
	for _, c := range cases {
		g, err := parseTest(c.src)
		if err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
		if _, err := generateCode(t, g, gen.GenOptions{Start: "main", Package: "gen", Recognize: true}); err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
	}
	gh.LeanRoute, gh.FramedRoute = nil, nil
	if taken == 0 || framed == 0 {
		t.Fatalf("%d direct and %d framed rules of the recognizer take the Flow route: the parity test exercises nothing", taken, framed)
	}
	goBin := filepath.Join(runtime.GOROOT(), "bin", "go")
	testGeneratedParsersCorpus(t, goBin, cases, gen.GenOptions{})
}

// flowRecognizerMutant, if set, changes the code generated by the Flow route. The
// negative control sets it to a wrong class test, which the parity test must reject.
var flowRecognizerMutant func([]byte) []byte

// invertClassTests inverts every range test of a character class in the code, as a printer would
// if it negated the test of a range.
func invertClassTests(code []byte) []byte {
	re := regexp.MustCompile(`ch >= (\d+) && ch <= (\d+)`)
	return re.ReplaceAllFunc(code, func(m []byte) []byte {
		sub := re.FindSubmatch(m)
		return []byte(fmt.Sprintf("!(ch >= %s && ch <= %s)", sub[1], sub[2]))
	})
}

// guardFirstCharacter matches the first-character guard of a literal alternative in generated code,
// with the character it tests.
var guardFirstCharacter = regexp.MustCompile(`if !\(x(\d+) && \(x(\d+) == (\d+)\)\) && p\.Depth`)

// shiftGuardFirstCharacters changes the character of every literal guard to the next one, as a printer
// would if it read the first set of an alternative one character off. An alternative whose first
// character is skipped by the guard is then never tried, so the parity test must reject it.
func shiftGuardFirstCharacters(code []byte) []byte {
	return guardFirstCharacter.ReplaceAllFunc(code, func(m []byte) []byte {
		sub := guardFirstCharacter.FindSubmatch(m)
		c, _ := strconv.Atoi(string(sub[3]))
		return []byte(fmt.Sprintf("if !(x%s && (x%s == %d)) && p.Depth", sub[1], sub[2], c+1))
	})
}

// flowRecognizerMutants are the wrong recognizers of the negative control, by PEGO_FLOW_MUTANT value.
// A dropped guard is not among them: a guard only skips an alternative that cannot match, so dropping
// one keeps the results and only the guard test in TestFlowRecognizerGuardsChoiceAlternatives sees it.
var flowRecognizerMutants = map[string]func([]byte) []byte{
	"class":   invertClassTests,
	"guard":   shiftGuardFirstCharacters,
	"capture": dropCaptures,
	"cut":     dropCuts,
	// A leader's growth is the runtime's: the printed body only reads the seed through a call of its own rule.
	// The mutants change those calls, as a printer would if it guarded the left-recursive alternative by a
	// wrong first set or lost the value the seed gives.
	"seed-guard": guardSeedReads,
	"seed-value": dropSeedValues,
	// The recovery of a body is inline: the error is recorded, the skip must make progress and starts from the mark.
	"recover-record": dropRecoveredErrors,
	"recover-zero":   dropZeroProgressCheck,
	"recover-rewind": skipWithoutRewind,
}

var (
	recordRecovered = regexp.MustCompile(`p\.Recovered = append\(p\.Recovered, (\w+)\)`)
	zeroProgress    = regexp.MustCompile(`(?m)^(\t+if p\.Pos == x\d+\.Pos)( \{\n\t+goto L\d+\n\t+\}\n)`)
	skipRewind      = regexp.MustCompile(`(?m)^(\t+x\d+ = p\.Keep\(x\d+\)\n)\t+p\.Reset\(x\d+\)\n`)
)

// dropRecoveredErrors recovers without recording the error, as a printer would if it lost the append.
func dropRecoveredErrors(code []byte) []byte {
	return recordRecovered.ReplaceAll(code, []byte("_ = $1"))
}

// dropZeroProgressCheck accepts a skip that consumed nothing (the condition stays, so that its label is used).
func dropZeroProgressCheck(code []byte) []byte {
	return zeroProgress.ReplaceAll(code, []byte("$1 && false$2"))
}

// skipWithoutRewind skips from the position where the body failed, not from the mark. A failed skip needs no
// mutant of its own: every caller of a recovery (a rule, a choice, a repetition) resets to its own mark.
func skipWithoutRewind(code []byte) []byte { return skipRewind.ReplaceAll(code, []byte("$1")) }

var (
	ruleBodyRef = regexp.MustCompile(`(?m)^\t(rules|recRules)\[(\d+)\]\.Body = (e\d+)$`)
	funcBody    = func(name string) *regexp.Regexp {
		return regexp.MustCompile(`(?ms)^func ` + name + `\(p \*rt\.Parser(?:, _ int)?\) \(\*rt\.Node, bool\) \{\n.*?^\}\n`)
	}
)

// mutateSelfCalls rewrites the calls that the body function of each rule makes to the rule itself: the call
// expression `p.Call(table[i], 0)` becomes repl(call).
func mutateSelfCalls(code []byte, repl func(call string) string) []byte {
	out := code
	for _, m := range ruleBodyRef.FindAllSubmatch(code, -1) {
		call := fmt.Sprintf("p.Call(%s[%s], 0)", m[1], m[2])
		fn := funcBody(string(m[3]))
		loc := fn.FindIndex(out)
		if loc == nil {
			continue
		}
		body := strings.ReplaceAll(string(out[loc[0]:loc[1]]), call, repl(call))
		out = append(append(append([]byte(nil), out[:loc[0]]...), body...), out[loc[1]:]...)
	}
	return out
}

// guardSeedReads reads the seed only where the next character is "1", as if the first set of the other
// alternatives were taken for that of the left-recursive one: on other inputs the alternative is skipped.
func guardSeedReads(code []byte) []byte {
	return mutateSelfCalls(code, func(call string) string {
		return "func() (*rt.Node, bool) { if p.Pos >= len(p.In) || p.In[p.Pos] != '1' { return nil, false }; return " + call + " }()"
	})
}

// dropSeedValues makes the call of the rule itself succeed or fail as before but give no value.
func dropSeedValues(code []byte) []byte {
	return mutateSelfCalls(code, func(call string) string {
		return "func() (*rt.Node, bool) { _, ok := " + call + "; return nil, ok }()"
	})
}

var setCut = regexp.MustCompile(`(?m)^(\t+cut\d+) = true$`)

// dropCuts drops every cut, as a printer would if it lowered a cut to nothing: the alternatives after a
// cut are tried again.
func dropCuts(code []byte) []byte {
	return setCut.ReplaceAll(code, []byte("$1 = false"))
}

var setCapture = regexp.MustCompile(`p\.SetCapture\w*\((\d+), (\w+)\)`)

// dropCaptures drops the recording of every capture, as a printer would if it took the captures of a rule
// without a value for dead: the actions and predicates that read them fail.
func dropCaptures(code []byte) []byte {
	return setCapture.ReplaceAll(code, []byte("_ = $2"))
}

// TestGeneratedFlowRecognizerMutantChild runs the parity test with the mutant that PEGO_FLOW_MUTANT
// names. It runs only as a child of TestGeneratedFlowRecognizerNegativeControl.
func TestGeneratedFlowRecognizerMutantChild(t *testing.T) {
	name := os.Getenv("PEGO_FLOW_MUTANT")
	if name == "" {
		t.Skip("run by TestGeneratedFlowRecognizerNegativeControl")
	}
	mutate, ok := flowRecognizerMutants[name]
	if !ok {
		t.Fatalf("unknown mutant %q", name)
	}
	mutated := 0
	flowRecognizerMutant = func(code []byte) []byte {
		mutant := mutate(code)
		if !bytes.Equal(mutant, code) {
			mutated++
		}
		return mutant
	}
	pinOrdinary(t)
	cases := genCorpus(t)
	testGeneratedParsersCorpus(t, filepath.Join(runtime.GOROOT(), "bin", "go"), cases, gen.GenOptions{})
	if mutated == 0 {
		t.Fatalf("the %s mutant changes no generated recognizer", name)
	}
}

// TestGeneratedFlowRecognizerNegativeControl checks that the parity test rejects each wrong recognizer
// of flowRecognizerMutants: the mutant child must fail with a recognition mismatch.
func TestGeneratedFlowRecognizerNegativeControl(t *testing.T) {
	t.Parallel()
	if testing.Short() {
		t.Skip("builds generated consumers")
	}
	for name := range flowRecognizerMutants {
		t.Run(name, func(t *testing.T) {
			cmd := exec.Command(os.Args[0], "-test.run=^TestGeneratedFlowRecognizerMutantChild$", "-test.count=1")
			cmd.Env = append(os.Environ(), "PEGO_FLOW_MUTANT="+name)
			out, err := cmd.CombinedOutput()
			if err == nil {
				t.Fatalf("the %s mutant passed the parity test:\n%s", name, out)
			}
			if !strings.Contains(string(out), "--- FAIL: TestGeneratedFlowRecognizerMutantChild") {
				t.Fatalf("the %s mutant child did not fail its test:\n%s", name, out)
			}
			// The rejection must come from the recognition comparison, not from a failure to build.
			if !strings.Contains(string(out), "recognize: ") {
				t.Fatalf("the %s mutant child failed without a recognition mismatch:\n%s", name, out)
			}
		})
	}
}

// TestFlowRecognizerGuardsChoiceAlternatives checks that the recognizer printed from Flow IR guards the
// alternatives of choices by their first characters: three alternatives are guarded by the class [uU],
// two by a quote and two by an apostrophe, each in the six, three and three places the recognizer's matchers
// are written. The guards are compared as conditions with the variable names removed, so the test does not
// depend on how the printer numbers its variables. Without the Analyze pass before Guards, the Flow route
// prints no guards for these choices and the comparison fails.
func TestFlowRecognizerGuardsChoiceAlternatives(t *testing.T) {
	t.Parallel()
	pinOrdinary(t)
	g, err := parseTest(`rule main = item* !.
rule item = uq / ident / sq
rule uq = [uU] "&" "\"" [^"]+ "\""
rule ident = [a-z]+ / "\"" [^"]+ "\""
rule sq = "'" [^']* "'" / [uU] "&'" [^']* "'"
`)
	if err != nil {
		t.Fatal(err)
	}
	code, err := generateCode(t, g, gen.GenOptions{Start: "main", Package: "gen", Recognize: true})
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, m := range guardCondition.FindAllSubmatch(code, -1) {
		got = append(got, string(variableName.ReplaceAll(m[1], []byte("x"))))
	}
	sort.Strings(got)
	var want []string
	for _, c := range []struct {
		cond string
		n    int
	}{{"x && (x == 117 || x == 85)", 6}, {"x && (x == 34)", 3}, {"x && (x == 39)", 3}} {
		for range c.n {
			want = append(want, c.cond)
		}
	}
	if !slices.Equal(got, want) {
		t.Errorf("the Flow recognizer guards %d alternatives, want %d:\ngot:  %q\nwant: %q", len(got), len(want), got, want)
	}
}

// guardCondition matches the first-character guard of a choice alternative in generated code, and
// variableName the numbered variables of the generated code.
var (
	guardCondition = regexp.MustCompile(`if !\((x\d+ && \([^\n]*?\))\) && p\.Depth`)
	variableName   = regexp.MustCompile(`x\d+`)
)

// TestFlowRecognizerFallbackMatchesEngine checks the fallback of the Flow route: a rule that flowRecRule
// refuses is printed from its framed body, called through the rule table, and the recognizer and parser of every
// input of the grammar must still agree with the engine. The test refuses every eligible rule, so that the
// framed body is exercised for all of them, and requires that each refused rule took the framed route.
func TestFlowRecognizerFallbackMatchesEngine(t *testing.T) {
	t.Parallel()
	if testing.Short() {
		t.Skip("builds generated consumers")
	}
	pinOrdinary(t)
	c := genCase{"fallback of the Flow recognizer",
		"rule main = ws item* !.\nrule ws = ([ ] / comment)*\nrule comment = \"--\" [^\\n]* / block_comment\nrule block_comment = \"/*\" (block_comment / !\"*/\" .)* \"*/\"\nrule item = [a-z]+ / [0-9]+\n",
		[]string{"", "a", "a 1 b2", "-- c\n a", "/* x */ a", "/* /* y */ */ 1", "/* open", "a -- tail", "@", "a /* x */ /* y */ 2", "--"}}
	refused, framed := map[string]bool{}, map[string]bool{}
	gh := &gogen.Hooks{}
	setGenHooks(t, gh)
	gh.RefuseFlowRecRule = func(r *compile.Rule) bool {
		if gen.RecFlowEligible(r) {
			refused[r.Name] = true
			return true
		}
		return false
	}
	gh.FramedRoute = func(table string, r *compile.Rule) {
		if table == "recRules" {
			framed[r.Name] = true
		}
	}
	testGeneratedParsersCorpus(t, filepath.Join(runtime.GOROOT(), "bin", "go"), []genCase{c}, gen.GenOptions{})
	if len(refused) == 0 {
		t.Fatal("no rule was refused: the fallback is not exercised")
	}
	for name := range refused {
		if !framed[name] {
			t.Errorf("rule %s was refused by flowRecRule but did not take the framed route", name)
		}
	}
}
