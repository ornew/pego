// tsGeneratedHeader starts every generated TypeScript file. The command line tool removes stale
// files of an earlier generation only if they start with it.
const tsGeneratedHeader = "// Code generated by pego. DO NOT EDIT.\n\n"

// tsRuntimeFileName is the file that holds the runtime, next to the parser (RuntimeEmbed).
const tsRuntimeFileName = "runtime.ts"

// tsEmbeddedRuntimeSpecifier is how parser.ts and types.ts import the runtime they sit next to. The
// .ts extension is the file's own name, which runtimes that strip types resolve as it is.
const tsEmbeddedRuntimeSpecifier = "./runtime.ts"

// tsTypesSpecifier is how parser.ts imports types.ts.
const tsTypesSpecifier = "./types.ts"

// tsPublicRuntime lists the runtime declarations that parser.ts re-exports: the names a user of the
// parser sees. The other exports of runtime.ts are the contract between the runtime and the code
// generated from a grammar.
var tsPublicRuntime = strings.Fields(`
	Value Unit CodePoints Bytes NodeField NodeJSON Node marshal SyntaxError SyntaxErrors ParseResult
	ParseOptions
	TraceKind TraceEvent Profile ProfileLocation SkipReasonCount RuleProfile ProfileSnapshot`)

// tsPublicControls lists the runtime declarations of the work controls that parser.ts re-exports
// only with -work-controls.
var tsPublicControls = strings.Fields(`CancellationSignal ParseInterruptionKind ParseInterruptionError`)

// tsRuntimeText returns the source of runtime.ts: the runtime, the invocation work controls and the
// observation code, as one module that exports every declaration the generated code uses.
var tsRuntimeText = sync.OnceValue(func() string {
	i := strings.Index(tsRuntimeSource, tsRuntimeMarker)
	var b strings.Builder
	b.WriteString(tsGeneratedHeader)
	b.WriteString("// The runtime of the TypeScript parsers generated by pego: nodes, errors, the parsing machine and\n")
	b.WriteString("// the controls of an invocation. It does not depend on a grammar; every parser imports it.\n\n")
	b.WriteString("/* eslint-disable */\n\n")
	b.WriteString(tsRuntimeSource[i+len(tsRuntimeMarker):])
	b.WriteString("\n// --- Invocation work controls ---\n")
	b.WriteString(tsWorkSource)
	b.WriteString("\n// --- Tracing ---\n")
	b.WriteString(tsTraceSource)
	b.WriteString("\n// --- Profiling ---\n")
	b.WriteString(tsProfileSource)
	return b.String()
})

// tsRuntimeFiles returns the file of the runtime alone.
func tsRuntimeFiles() []gen.GeneratedFile {
	return []gen.GeneratedFile{{Path: tsRuntimeFileName, Content: []byte(tsRuntimeText())}}
}

var tsExportDecl = regexp.MustCompile(`(?m)^export (?:abstract )?(function|class|const|let|interface|type) ([\p{L}\p{N}_$]+)`)

// tsRuntimeExports maps the exported names of runtime.ts to whether they are only types.
var tsRuntimeExports = sync.OnceValue(func() map[string]bool {
	exports := map[string]bool{}
	for _, m := range tsExportDecl.FindAllStringSubmatch(tsRuntimeText(), -1) {
		// An interface merged with a class of the same name is a value.
		isType := m[1] == "interface" || m[1] == "type"
		if prev, ok := exports[m[2]]; ok {
			isType = isType && prev
		}
		exports[m[2]] = isType
	}
	return exports
})

// tsFiles assembles the files of a parser from the code generated from the grammar (body) and the
// declarations of its types (types, empty without opts.Types).
func tsFiles(opts gen.GenOptions, body, types string) []gen.GeneratedFile {
	spec := tsEmbeddedRuntimeSpecifier
	if opts.Runtime == gen.RuntimeImport {
		spec = opts.RuntimeModule
	}
	var files []gen.GeneratedFile
	var parser strings.Builder
	parser.WriteString(tsGeneratedHeader)
	parser.WriteString("// A parser generated from a PEGO grammar; see parse below. It imports its runtime.\n\n")
	parser.WriteString("/* eslint-disable */\n\n")
	used := tsIdentifiers(body)
	exports := tsRuntimeExports()
	var names []string
	for name := range used {
		if _, ok := exports[name]; ok {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	parser.WriteString("import {" + tsImportNames(names, exports) + "} from " + tsString(spec) + ";\n")
	if types != "" {
		parser.WriteString("import type * as Types from " + tsString(tsTypesSpecifier) + ";\n")
	}
	parser.WriteString("\n// The names of the runtime that users of the parser need.\n")
	var values, typs []string
	public := slices.Clone(tsPublicRuntime)
	if opts.WorkControls {
		public = append(public, tsPublicControls...)
	}
	for _, name := range public {
		export := name
		if name == "ParseOptions" && !opts.WorkControls {
			// Without work controls the options have no cancellation or limits.
			export = "PlainParseOptions as ParseOptions"
			name = "PlainParseOptions"
		}
		if exports[name] {
			typs = append(typs, export)
		} else {
			values = append(values, export)
		}
	}
	if len(values) > 0 {
		parser.WriteString("export {" + strings.Join(values, ", ") + "} from " + tsString(spec) + ";\n")
	}
	if len(typs) > 0 {
		parser.WriteString("export type {" + strings.Join(typs, ", ") + "} from " + tsString(spec) + ";\n")
	}
	if types != "" {
		// parser.ts stays the single entry point: the types of the grammar are exported from it too.
		parser.WriteString("\n// The types of the grammar.\nexport type * from " + tsString(tsTypesSpecifier) + ";\n")
	}
	parser.WriteString("\n")
	parser.WriteString(body)
	if opts.Runtime != gen.RuntimeImport {
		files = append(files, gen.GeneratedFile{Path: tsRuntimeFileName, Content: []byte(tsRuntimeText())})
	}
	files = append(files, gen.GeneratedFile{Path: "parser.ts", Content: []byte(parser.String())})
	if types != "" {
		var t strings.Builder
		t.WriteString(tsGeneratedHeader)
		t.WriteString("// The types of a PEGO grammar, as the typed parseAST of parser.ts returns them.\n\n")
		t.WriteString("/* eslint-disable */\n\n")
		t.WriteString("import type {Node as RuntimeNode} from " + tsString(spec) + ";\n\n")
		t.WriteString(types)
		files = append(files, gen.GeneratedFile{Path: "types.ts", Content: []byte(t.String())})
	}
	return files
}

// tsImportNames renders the names of an import list; names only used as types are imported as types.
func tsImportNames(names []string, exports map[string]bool) string {
	parts := make([]string, len(names))
	for i, name := range names {
		if exports[name] {
			parts[i] = "type " + name
		} else {
			parts[i] = name
		}
	}
	return strings.Join(parts, ", ")
}

// tsIdentifiers returns the identifiers that code uses: those outside comments and strings (the
// parts of template literals included) that do not follow a dot, which only names a property.
func tsIdentifiers(code string) map[string]bool {
	ids := map[string]bool{}
	// braces counts, for each open template literal substitution, the unclosed braces inside it.
	var braces []int
	i := 0
	template := func() {
		// i is after a backtick or a closing brace of a substitution: read template text.
		for i < len(code) {
			switch code[i] {
			case '\\':
				i += 2
			case '`':
				i++
				return
			case '$':
				if i+1 < len(code) && code[i+1] == '{' {
					i += 2
					braces = append(braces, 0)
					return
				}
				i++
			default:
				i++
			}
		}
	}
	for i < len(code) {
		c := code[i]
		switch {
		case c == '/' && i+1 < len(code) && code[i+1] == '/':
			for i < len(code) && code[i] != '\n' {
				i++
			}
		case c == '/' && i+1 < len(code) && code[i+1] == '*':
			j := strings.Index(code[i+2:], "*/")
			if j < 0 {
				return ids
			}
			i += j + 4
		case c == '"' || c == '\'':
			i++
			for i < len(code) && code[i] != c {
				if code[i] == '\\' {
					i++
				}
				i++
			}
			i++
		case c == '`':
			i++
			template()
		case c == '{':
			if n := len(braces); n > 0 {
				braces[n-1]++
			}
			i++
		case c == '}':
			if n := len(braces); n > 0 {
				if braces[n-1] == 0 {
					braces = braces[:n-1]
					i++
					template()
					continue
				}
				braces[n-1]--
			}
			i++
		default:
			r, size := utf8.DecodeRuneInString(code[i:])
			if r == '_' || r == '$' || unicode.IsLetter(r) {
				j := i + size
				for j < len(code) {
					r, size := utf8.DecodeRuneInString(code[j:])
					if r != '_' && r != '$' && !unicode.IsLetter(r) && !unicode.IsDigit(r) {
						break
					}
					j += size
				}
				// A property name follows a dot, but a spread (...x) names a variable.
				prop := i > 0 && code[i-1] == '.' && !(i > 2 && code[i-2] == '.' && code[i-3] == '.')
				if !prop {
					ids[code[i:j]] = true
				}
				i = j
				continue
			}
			if unicode.IsDigit(r) {
				// A number, including its suffixes and exponent: not an identifier.
				for i < len(code) && (unicode.IsLetter(rune(code[i])) || unicode.IsDigit(rune(code[i])) || code[i] == '_' || code[i] == '.') {
					i++
				}
				continue
			}
			i += size
		}
	}
	return ids
}
