package engine

import (
	"strings"
	"testing"

	"github.com/ornew/pego/internal/gen"
	"github.com/ornew/pego/internal/gen/gogen"
)

func TestTrimComments(t *testing.T) {
	const src = `// Code generated by pego. DO NOT EDIT.

// Package p is a parser.
package p

// Exported is documented.
type Exported struct {
	// A is documented.
	A int
}

// Method is documented.
func (e *Exported) Method() {
	// kept inside an exported declaration
	_ = e
}

// helper explains an unexported function.
func helper() {
	// explains a statement
	_ = 1 // trailing
}

// rule main
func u1() {}

//go:noinline
func u2() {}

//nolint:unused
func u3() {}

func u4() {
	/*line other.go:10*/ _ = 1
}

// unexported method of an exported type.
func (e *Exported) method() {}

// tbl explains an unexported variable.
var tbl = 1
`
	got, err := gogen.TrimComments([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	out := string(got)
	for _, want := range []string{"Code generated", "Package p", "Exported is documented", "A is documented", "Method is documented", "kept inside", "// rule main", "//go:noinline", "//nolint:unused", "/*line other.go:10*/"} {
		if !strings.Contains(out, want) {
			t.Errorf("trimmed source lost %q:\n%s", want, out)
		}
	}
	for _, gone := range []string{"explains an unexported function", "explains a statement", "trailing", "unexported method", "explains an unexported variable"} {
		if strings.Contains(out, gone) {
			t.Errorf("trimmed source kept %q:\n%s", gone, out)
		}
	}
}

// Generate leaves the comments of unexported code out, except the markers that name the rule.
func TestGenerateTrimsComments(t *testing.T) {
	g, err := parseTest("rule main = item+\nrule item = [a-z]+ \";\"\n")
	if err != nil {
		t.Fatal(err)
	}
	opts := gen.GenOptions{Package: "p", Start: "main", Runtime: gen.RuntimeImport, Types: true, Module: "example.com/p"}
	files, err := Generate(g, opts)
	if err != nil {
		t.Fatal(err)
	}
	src := string(files[0].Content)
	if strings.Contains(src, "called as by") || strings.Contains(src, "body inlined") {
		t.Errorf("generated source keeps route comments:\n%s", src)
	}
	opts.KeepComments = true
	files, err = Generate(g, opts)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(files[0].Content), "called as by") {
		t.Error("keepComments dropped the route comments")
	}
}
