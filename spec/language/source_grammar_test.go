func TestSourceGrammarTrivia(t *testing.T) {
	p, _ := sourceGrammar(t)
	for _, src := range []string{
		`rule main = (/* inside */ "//not comment") => Node{Text: "/*not comment*/"}`,
		`rule main = { /* inside */ x:=1 }`,
		"rule main = \"a\rb\"; rule class = [a\rb]",
		`rule main = "x" #atomic #repeat(-0) @meta(- 1)`,
		`rule main = "x" @name ("y")`,
		// A comment may sit between two statements.
		"rule a = \"x\" ; /* x */ // after\nrule b = \"y\"",
		"rule a = \"x\" ; /* x */\n// lead\nrule b = \"y\"",
	} {
		if _, err := zp.ParseGrammar(src); err != nil {
			t.Fatalf("reference rejects %q: %v", src, err)
		}
		n, err := p.Parse(src)
		if err != nil {
			t.Fatalf("source rejects %q: %v", src, err)
		}
		comments := elems(sourceField(t, n, "Comments"))
		if strings.Contains(src, "/* inside */") && (len(comments) != 1 || comments[0].Type() != "InlineComment") {
			t.Fatalf("expression comment lost: %v", comments)
		}
		for _, c := range comments {
			if c == nil {
				t.Fatal("nil in []Comment")
			}
		}
	}
	for _, src := range []string{
		`rule main = "x" @ name`, `rule main = "x" @/* c */name`, `rule main = "x" #repeat(-1)`,
		`rule main = "x" # atomic`, `rule main = "x" #/* c */atomic`,
		`rule main = "x" # recover(skip=";")`, `rule main = "x" #recover (skip=";")`,
		`rule main = "x" #repeat /* c */(2)`, `rule main = "x" #repeat (2)`,
		// A group's multiline mode ends at its closing parenthesis.
		"type A ~ (B)\n  | C", "rule a = x:\"a\" => $x.(Match)\n  == $x",
	} {
		if _, err := zp.ParseGrammar(src); err == nil {
			t.Fatalf("reference accepted %q", src)
		}
		if _, err := p.Parse(src); err == nil {
			t.Fatalf("source accepted %q", src)
		}
	}
}

func TestSourceGrammarPackageRecovery(t *testing.T) {
	p, _ := sourceGrammar(t)
	for _, src := range []string{"package\nrule after = \"ok\"", "// leading\npackage ; rule after = \"ok\""} {
		for _, backend := range []zp.Backend{zp.Closure, zp.Bytecode, zp.BytecodeIterative} {
			n, err := p.Parse(src, zp.WithBackend(backend), zp.WithExpectations())
			var syntaxErrors zp.SyntaxErrors
			if !errors.As(err, &syntaxErrors) || len(syntaxErrors) != 1 || !strings.Contains(err.Error(), "expected package name") {
				t.Fatalf("%v: %v", backend, err)
			}
			if sourceField(t, n, "Pkg").Type() != "error" {
				t.Fatal("package error lost")
			}
			ds := sourceDecls(t, n)
			if len(ds) != 1 || sourceText(t, ds[0], "Name") != "after" {
				t.Fatal("package recovery lost next declaration")
			}
		}
	}
}

// TestSourceGrammarOperatorsPlacement checks that the source grammar and the reference parser
// agree on where #operators { is valid: only as the whole body of a rule, with its { on the same
// line.
func TestSourceGrammarOperatorsPlacement(t *testing.T) {
	p, _ := sourceGrammar(t)
	for _, tc := range []struct {
		name, src string
		valid     bool
	}{
		{"whole body", `rule a = #operators { operand "x" }`, true},
		{"typed body", "type T = { Text string }\nrule a T = #operators { operand \"x\" }", true},
		{"after an expression", `rule a = "a" #operators { operand "x" }`, false},
		{"in a group", `rule a = ("a" / #operators { operand "x" })`, false},
		{"brace on the next line", "rule a = #operators\n{ operand \"x\" }", false},
		{"no brace", `rule a = #operators`, false},
		{"arguments", `rule a = #operators( operand "x" )`, false},
		{"reference and predicate", `rule operators = "x"` + "\n" + `rule a = operators {1 == 1}`, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, refErr := zp.ParseGrammar(tc.src)
			_, err := p.Parse(tc.src, zp.RecognizeOnly())
			if (refErr == nil) != tc.valid {
				t.Errorf("reference parser: valid %v, want %v (%v)", refErr == nil, tc.valid, refErr)
			}
			if (err == nil) != tc.valid {
				t.Errorf("source grammar: valid %v, want %v (%v)", err == nil, tc.valid, err)
			}
		})
	}
}
