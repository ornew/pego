func sourceGrammar(t *testing.T) (*zp.Parser, string) {
	t.Helper()
	src, err := os.ReadFile("../../zeroparse.zp")
	if err != nil {
		t.Fatal(err)
	}
	p, err := zp.CompileSource(string(src), "main")
	if err != nil {
		t.Fatal(err)
	}
	return p, string(src)
}

func sourceField(t *testing.T, n *zp.Node, name string) *zp.Node {
	t.Helper()
	if n == nil {
		t.Fatalf("nil node for field %s", name)
	}
	child, ok := n.Field(name).(*zp.Node)
	if !ok || child == nil {
		t.Fatalf("%s.%s is %T, want node", n.Type(), name, n.Field(name))
	}
	return child
}

// sourceText returns the text held by field name of n, a named string node.
func sourceText(t *testing.T, n *zp.Node, name string) string {
	t.Helper()
	field := sourceField(t, n, name)
	text := field.Text()
	if field.Kind() != zp.KindString {
		t.Fatalf("%s.%s has no text", n.Type(), name)
	}
	return text
}

// elems returns the elements of the tuple or list n.
func elems(n *zp.Node) []*zp.Node {
	var out []*zp.Node
	for _, e := range n.Elems() {
		out = append(out, e)
	}
	return out
}

func sourceDecls(t *testing.T, n *zp.Node) []*zp.Node {
	t.Helper()
	if n == nil || n.Type() != "File" {
		t.Fatalf("source root: %v", n)
	}
	return elems(sourceField(t, n, "Decls"))
}

func TestSourceGrammarMatchesDocumentation(t *testing.T) {
	_, src := sourceGrammar(t)
	doc, err := os.ReadFile("syntax.md")
	if err != nil {
		t.Fatal(err)
	}
	blocks := zpCodeBlocks(string(doc))
	if len(blocks) != 1 || !strings.Contains(string(doc), "`zeroparse.zp`") || strings.Contains(string(doc), "](http") || strings.Contains(string(doc), "## Full Grammar") {
		t.Fatal("expected one simple grammar and a reference to the full source and no external link")
	}
	g, err := zp.ParseGrammar(src)
	if err != nil {
		t.Fatal(err)
	}
	if blocks[0] != grammar.FormatSyntax(g) {
		t.Fatal("displayed simple grammar is stale")
	}
	tmpl, err := template.ParseFiles("syntax.md.tmpl")
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err := tmpl.Execute(&generated, struct{ Simple string }{blocks[0]}); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(doc, generated.Bytes()) {
		t.Fatal("syntax.md is stale; run go generate ./spec/language")
	}
}

func TestSourceGrammarNodeConstructors(t *testing.T) {
	p, _ := sourceGrammar(t)
	const src = `type Foo = { A node[string]; B []Foo }
type Word = { Text string }
rule word = "x" => Word{Text: "0"}
rule empty = "x" => []Foo{}
rule nested = v1:"x" => [][]Foo{[]Foo{Foo{A: $v1}},}
rule args = "x" => Word{Text: "a", Text: "b",}
rule index = xs:"x"+ => list($xs)[0][len($xs) - 1]
rule capture = xs:(y:"x")+ => map($xs, (i) => i.$y)
rule cast = x:"x" => $x.([]Foo | *Word).Len
type Meet ~ []Foo & *Word | _ & _|_
type Tuple ~ () | (Foo) | (Foo,) | ( Foo , node[Word, (Foo, Word,)] ) | []node[Word]
type Unnamed ~ {} | []{ A Foo; B { C Word } }
type Num = node[string]
rule num = x:"1" => Num{$x,}
rule tuples = "x" => ((), (Foo{},), ( 1 , "a" , ), (2), (1, (2,)))
`
	if _, err := zp.ParseGrammar(src); err != nil {
		t.Fatal(err)
	}
	// A constructor takes named fields or positional values, not both.
	const mixed = "type Num = node[string]\nrule num = x:\"x\" => Num{$x, Text: \"0\"}"
	if _, err := zp.ParseGrammar(mixed); err == nil {
		t.Fatal("the reader accepts a mixed constructor")
	}
	for _, backend := range []zp.Backend{zp.Closure, zp.Bytecode, zp.BytecodeIterative} {
		if _, err := p.Parse(mixed, zp.WithBackend(backend)); err == nil {
			t.Fatalf("%v: the source grammar accepts a mixed constructor", backend)
		}
		n, err := p.Parse(src, zp.WithBackend(backend))
		if err != nil {
			t.Fatal(err)
		}
		defs := sourceDecls(t, n)
		text := sourceField(t, defs[2], "Action")
		if text.Type() != "Constructor" || len(elems(sourceField(t, text, "Inits"))) != 1 {
			t.Fatal("text struct source fields lost")
		}
		empty := sourceField(t, defs[3], "Action")
		if empty.Type() != "ListConstructor" || len(elems(sourceField(t, empty, "Items"))) != 0 {
			t.Fatal("empty typed source list lost")
		}
		nested := sourceField(t, defs[4], "Action")
		if sourceField(t, nested, "Elem").Type() != "ListType" || elems(sourceField(t, nested, "Items"))[0].Type() != "ListConstructor" {
			t.Fatal("nested typed source list lost")
		}
		if inits := sourceField(t, sourceField(t, defs[5], "Action"), "Inits"); len(elems(inits)) != 2 {
			t.Fatal("repeated fields and a trailing comma must remain parseable")
		}
		index := sourceField(t, defs[6], "Action")
		if index.Type() != "BinaryOp" || index.Field("Op") != "[]" || sourceField(t, index, "L").Type() != "BinaryOp" || sourceField(t, index, "R").Type() != "BinaryOp" {
			t.Fatal("index structure lost")
		}
		lambda := elems(sourceField(t, sourceField(t, defs[7], "Action"), "Args"))[1]
		if access := sourceField(t, lambda, "Body"); access.Type() != "CaptureAccess" || sourceField(t, access, "Capture").Type() != "CaptureRef" {
			t.Fatal("capture access structure lost")
		}
		member := sourceField(t, defs[8], "Action")
		if cast := sourceField(t, member, "X"); member.Type() != "FieldAccess" || cast.Type() != "Cast" || sourceField(t, cast, "Type").Type() != "JoinType" {
			t.Fatal("cast structure lost")
		}
		// & binds tighter than |; _ is a name and _|_ is one token.
		meet := sourceField(t, defs[9], "Type")
		l, r := sourceField(t, meet, "L"), sourceField(t, meet, "R")
		if meet.Type() != "JoinType" || l.Type() != "MeetType" || r.Type() != "MeetType" ||
			sourceField(t, r, "L").Type() != "TypeRef" || sourceField(t, r, "R").Type() != "Bottom" {
			t.Fatal("meet structure lost")
		}
		// One type without a comma is a group, and type arguments follow the name directly.
		var alts []*zp.Node
		for u := sourceField(t, defs[10], "Type"); ; u = sourceField(t, u, "L") {
			if u.Type() != "JoinType" {
				alts = append([]*zp.Node{u}, alts...)
				break
			}
			alts = append([]*zp.Node{sourceField(t, u, "R")}, alts...)
		}
		want := []struct {
			typ   string
			count int
		}{{"TupleType", 0}, {"TypeGroup", -1}, {"TupleType", 1}, {"TupleType", 2}, {"ListType", -1}}
		if len(alts) != len(want) {
			t.Fatalf("tuple alternatives: got %d", len(alts))
		}
		for i, w := range want {
			if alts[i].Type() != w.typ || w.count >= 0 && len(elems(sourceField(t, alts[i], "Types"))) != w.count {
				t.Fatalf("tuple alternative %d: got %s", i, alts[i].Type())
			}
		}
		app := elems(sourceField(t, alts[3], "Types"))[1]
		if args := elems(sourceField(t, app, "Args")); app.Type() != "TypeApp" || len(args) != 2 || args[1].Type() != "TupleType" {
			t.Fatal("type application structure lost")
		}
		if sourceField(t, alts[4], "Type").Type() != "TypeApp" {
			t.Fatal("[] must apply to a type application")
		}
		unnamed := sourceField(t, defs[11], "Type")
		empty, list := sourceField(t, unnamed, "L"), sourceField(t, unnamed, "R")
		if empty.Type() != "StructType" || len(elems(sourceField(t, empty, "Fields"))) != 0 || list.Type() != "ListType" {
			t.Fatal("unnamed struct structure lost")
		}
		fields := elems(sourceField(t, sourceField(t, list, "Type"), "Fields"))
		if len(fields) != 2 || sourceField(t, fields[1], "Type").Type() != "StructType" {
			t.Fatal("unnamed struct fields lost")
		}
		if def := sourceField(t, defs[12], "Type"); def.Type() != "TypeApp" || sourceText(t, def, "Name") != "node" || len(elems(sourceField(t, def, "Args"))) != 1 {
			t.Fatal("node type definition lost")
		}
		if conv := sourceField(t, defs[13], "Action"); conv.Type() != "Constructor" || len(elems(sourceField(t, conv, "Args"))) != 1 || len(elems(sourceField(t, conv, "Inits"))) != 0 {
			t.Fatal("positional constructor lost")
		}
		// One expression without a comma is a group; any other parentheses form a tuple.
		tuples := elems(sourceField(t, sourceField(t, defs[14], "Action"), "Elems"))
		wantTuple := []struct {
			typ   string
			count int
		}{{"ActionTuple", 0}, {"ActionTuple", 1}, {"ActionTuple", 2}, {"ActionGroup", -1}, {"ActionTuple", 2}}
		if len(tuples) != len(wantTuple) || sourceField(t, defs[14], "Action").Type() != "ActionTuple" {
			t.Fatalf("tuple literal: got %d elements", len(tuples))
		}
		for i, w := range wantTuple {
			if tuples[i].Type() != w.typ || w.count >= 0 && len(elems(sourceField(t, tuples[i], "Elems"))) != w.count {
				t.Fatalf("tuple literal element %d: got %s", i, tuples[i].Type())
			}
		}
	}
}

