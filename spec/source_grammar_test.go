func sourceGrammar(t *testing.T) (*pego.Parser, string) {
	t.Helper()
	src, err := os.ReadFile("../pego.pego")
	if err != nil {
		t.Fatal(err)
	}
	p, err := pego.CompileSource(string(src), "main")
	if err != nil {
		t.Fatal(err)
	}
	return p, string(src)
}

func sourceField(t *testing.T, n *pego.Node, name string) *pego.Node {
	t.Helper()
	if n == nil {
		t.Fatalf("nil node for field %s", name)
	}
	child, ok := n.Field(name).(*pego.Node)
	if !ok || child == nil {
		t.Fatalf("%s.%s is %T, want node", n.Type(), name, n.Field(name))
	}
	return child
}

func sourceDefs(t *testing.T, n *pego.Node) []*pego.Node {
	t.Helper()
	if n == nil || n.Type() != "File" {
		t.Fatalf("source root: %v", n)
	}
	return sourceField(t, n, "Defs").Children
}

func TestSourceGrammarMatchesDocumentation(t *testing.T) {
	_, src := sourceGrammar(t)
	doc, err := os.ReadFile("syntax.md")
	if err != nil {
		t.Fatal(err)
	}
	blocks := pegoCodeBlocks(string(doc))
	if len(blocks) != 1 || !strings.Contains(string(doc), "https://github.com/ornew/pego/blob/main/pego.pego") || strings.Contains(string(doc), "## Full Grammar") {
		t.Fatal("expected one simple grammar and a link to the canonical full source")
	}
	g, err := pego.ParseGrammar(src)
	if err != nil {
		t.Fatal(err)
	}
	if blocks[0] != grammar.FormatSyntax(g) {
		t.Fatal("displayed simple grammar is stale")
	}
	tmpl, err := template.ParseFiles("syntax.md.tmpl")
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err := tmpl.Execute(&generated, struct{ Simple string }{blocks[0]}); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(doc, generated.Bytes()) {
		t.Fatal("syntax.md is stale; run go generate ./spec")
	}
}

